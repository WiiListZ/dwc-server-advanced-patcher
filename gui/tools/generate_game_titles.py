"""Refresh the embedded names for game IDs in gamedefs.csv.

Names come from GameTDB's English Wii title database as distributed by Dolphin.
Run from any directory: python gui/tools/generate_game_titles.py
"""

import csv
from pathlib import Path
from urllib.request import urlopen


ROOT = Path(__file__).resolve().parents[2]
SOURCE = "https://raw.githubusercontent.com/dolphin-emu/dolphin/master/Data/Sys/wiitdb-en.txt"
DESTINATION = ROOT / "gui" / "src" / "game_titles.hpp"


def cpp_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


with urlopen(SOURCE, timeout=20) as response:
    lines = response.read().decode("utf-8-sig").splitlines()
titles = {}
for line in lines:
    if " = " not in line:
        continue
    game_id, title = line.split(" = ", 1)
    if len(game_id) in (4, 6):
        titles[game_id] = title.strip()

with (ROOT / "gamedefs.csv").open(encoding="utf-8", newline="") as source:
    variants = sorted({row["Title"][:5] for row in csv.DictReader(source)})

selected = {}
for variant in variants:
    prefix, kind = variant[:4], variant[4]
    choices = sorted(key for key in titles if key.startswith(prefix))
    if not choices:
        raise RuntimeError(f"No title for {prefix}")
    preferred = prefix + "01" if kind == "D" else prefix
    fallback = prefix if prefix in titles else choices[0]
    selected[variant] = titles[preferred if preferred in titles else fallback]

output = [
    "// Generated by gui/tools/generate_game_titles.py from GameTDB via Dolphin.",
    "// Source: https://www.gametdb.com/Wii/Downloads",
    "#pragma once",
    "#include <string_view>",
    "#include <utility>",
    "",
    "inline constexpr std::pair<std::string_view, std::string_view> kGameTitles[] = {",
]
output += [f"    {{{cpp_string(key)}, {cpp_string(title)}}}," for key, title in selected.items()]
output += ["};", ""]
DESTINATION.write_text("\n".join(output), encoding="utf-8")
print(f"Wrote {len(selected)} game names to {DESTINATION}")
