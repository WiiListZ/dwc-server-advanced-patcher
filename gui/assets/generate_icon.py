"""Rasterize docs/logo.svg into desktop icons and embedded GLFW pixels.

Requires Pillow only when regenerating the checked-in assets.
"""

from pathlib import Path

from PIL import Image, ImageDraw


assets = Path(__file__).resolve().parent
def render(size: int) -> Image.Image:
    scale = size * 4 / 32
    canvas = Image.new("RGBA", (size * 4, size * 4))
    draw = ImageDraw.Draw(canvas)

    def circle(x: float, y: float, radius: float, color: str) -> None:
        draw.ellipse(((x - radius) * scale, (y - radius) * scale,
                      (x + radius) * scale, (y + radius) * scale), fill=color)

    circle(16, 16, 16, "#A6E0F8")
    circle(16, 16, 13, "#00A0E6")
    for radius in (4, 7.2, 10.4):
        bounds = ((11 - radius) * scale, (16 - radius) * scale,
                  (11 + radius) * scale, (16 + radius) * scale)
        draw.arc(bounds, -45, 45, fill="white", width=round(2.2 * scale))
        for sign in (-1, 1):
            circle(11 + radius / 2**0.5, 16 + sign * radius / 2**0.5, 1.1, "white")
    circle(11, 16, 1.9, "white")
    return canvas.resize((size, size), Image.Resampling.LANCZOS)


render(256).save(assets / "logo.png")
render(256).save(assets / "logo.ico", sizes=[(16, 16), (32, 32), (48, 48), (256, 256)])

pixels = render(32).tobytes()
lines = ["#pragma once", "", "// RGBA pixels from docs/logo.svg, generated by assets/generate_icon.py.",
         "inline constexpr unsigned char kLogoPixels[] = {"]
for start in range(0, len(pixels), 16):
    lines.append("    " + ", ".join(str(value) for value in pixels[start:start + 16]) + ",")
lines.append("};")
(assets.parent / "src" / "logo_pixels.hpp").write_text("\n".join(lines) + "\n", encoding="utf-8")
